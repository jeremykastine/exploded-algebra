const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const context = vm.createContext({ window: {} });
vm.runInContext(fs.readFileSync(path.join(__dirname, "../exploded-algebra-renderer.js"), "utf8"), context);
const renderer = context.window.ExplodedAlgebraRenderer;
const node = (type, ...args) => new renderer.ExprNode(type, args);
const value = text => new renderer.ExprNode("value", [], text);
const code = renderer.expressionToCodeMarkup;

assert.equal(code(node("prod", value("2"), value("x"), value("x"))), "2*x*x");
assert.equal(code(node("prod", node("sum", value("x"), value("2")), node("inv", node("sum", value("x"), value("3"))))), "(x   +   2) / (x   +   3)");
assert.equal(code(node("inv", node("prod", value("2"), value("x")))), "1 / (2*x)");
assert.equal(code(node("inv", node("inv", value("x")))), "1 / (1 / x)");
assert.equal(code(node("prod", value("3"), node("inv", value("-1")))), "3 / (-1)");
assert.equal(code(node("sum", value("x"), node("prod", value("-1"), node("sum", value("y"), value("2"))))), "x - (y   +   2)");
assert.equal(code(value('<img src=x onerror="alert(1)">')), "&lt;img src=x onerror=&quot;alert(1)&quot;&gt;");
const placeholder = value("");
placeholder.isBuilderPlaceholder = true;
assert.equal(code(placeholder, true), "□");
const sequence = node("sum", value("2"), value("x"));
sequence.isBuilderSequence = true;
sequence.builderOperators = ["prod", "sum"];
assert.equal(code(sequence, true), "2*x   +   ");
const preview = node("prod", value("6"), node("prod", value("2"), value("3")));
preview.isReplacementBuilderPreview = true;
preview.rewriteOriginalOpacity = 0.28;
const markup = code(preview, true);
assert(markup.includes('data-code="6" style="opacity:0.28"'));
assert(markup.includes('class="workspace-rewrite-entry">2*3</span>'));
assert(!markup.includes('>6<'), "The fading original must not contaminate copied expression text");
preview.preserveOriginalLayoutWhenEmpty = true;
assert.equal(code(preview, true), '<span style="opacity:0.28">6</span>');
console.log("Code notation preserves grouping, explicit operators, safe text, and live replacement previews.");
